-- ==========================================
-- TABELA: SALAS
-- ==========================================

CREATE TABLE salas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR(20) NOT NULL,
    bloco VARCHAR(10) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    capacidade INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL
);

